import assert from "node:assert/strict";
import { once } from "node:events";
import { appendFile, mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";
import { chromium, expect, type Browser } from "@playwright/test";
import { startProgressServer } from "../ralph-server.js";

test("live progress page renders updates safely and supports filtering on desktop and mobile", { timeout: 30000 }, async () => {
  const root = await mkdtemp(path.join(tmpdir(), "ralph-server-ui-"));
  const server = await startProgressServer(root, 0);
  let browser: Browser | undefined;
  try {
    browser = await chromium.launch();
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${(server.address() as AddressInfo).port}`);
    await expect(page.getByText("Waiting for progress.txt", { exact: true })).toBeVisible();
    const file = path.join(root, "progress.txt");
    const record = (run: string, event: string, details: unknown) => `\n[${new Date().toISOString()}] ${run} — ${event}\n${JSON.stringify(details, null, 2)}\n`;
    await writeFile(file, record("run-1", "Run started", { goal: "Improve learner retention", iterations: 5 }) + record("run-1", "Phase started", { iteration: 1, phase: "verify" }));
    await expect(page.locator("#goal")).toHaveText("Improve learner retention");
    await expect(page.locator("#phase")).toHaveText("verify");
    await expect(page.locator("#iteration")).toHaveText("1 / 5");
    const phase = page.locator(".entry").filter({ hasText: "Phase started" });
    await phase.locator("summary").click();
    await appendFile(file, record("run-1", "Check passed", { command: "npm test", summary: '<img src=x onerror="window.injected=true">' }));
    await expect(page.locator(".entry")).toHaveCount(3);
    await expect(phase).toHaveAttribute("open", "");
    await expect(phase.locator("summary")).toBeFocused();
    await page.locator(".entry").filter({ hasText: "Check passed" }).locator("summary").click();
    await expect(page.getByText('<img src=x onerror="window.injected=true">', { exact: true })).toBeVisible();
    assert.equal(await page.evaluate(() => "injected" in window), false);
    assert.equal(await page.locator("#events img").count(), 0);
    await page.route("**/api/progress", route => route.abort());
    await expect(page.locator("#notice")).toBeVisible();
    await expect(page.locator(".entry")).toHaveCount(3);
    await page.unroute("**/api/progress");
    await expect(page.locator("#notice")).toBeHidden();
    await page.locator("#search").fill("npm test");
    await expect(page.locator(".entry")).toHaveCount(1);
    await page.locator("#search").fill("");
    await page.locator("#live").uncheck();
    await appendFile(file, record("run-2", "Run started", { goal: "Another goal" }));
    await page.waitForTimeout(1400);
    await expect(page.locator("#run option")).toHaveCount(2);
    await page.locator("#live").check();
    await expect(page.locator("#goal")).toHaveText("Another goal");
    await page.locator("#run").selectOption("run-1");
    await expect(page.locator(".entry")).toHaveCount(3);
    await page.locator("#raw-button").click();
    await expect(page.locator("#raw-text")).toContainText("Another goal");
    await page.locator("#raw-button").click();
    await mkdir("test-results", { recursive: true });
    await page.screenshot({ path: "test-results/progress-desktop.png", fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await page.screenshot({ path: "test-results/progress-mobile.png", fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await writeFile(file, "A plain log without structured events");
    await expect(page.getByText("Plain text log", { exact: true })).toBeVisible();
    await page.locator("#raw-button").click();
    await expect(page.locator("#raw-text")).toHaveText("A plain log without structured events");
    await rm(file);
    await expect(page.getByText("Waiting for progress.txt", { exact: true })).toBeVisible();
    assert.deepEqual(errors, []);
  } finally {
    await browser?.close();
    server.closeAllConnections(); server.close(); await once(server, "close");
    await rm(root, { recursive: true, force: true });
  }
});
